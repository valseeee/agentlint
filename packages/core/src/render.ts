import { instructionLabel } from "./discovery.js";
import type { AnalysisReport, Finding, Locale, ReportDiff } from "./types.js";

export function renderMarkdownReport(report: AnalysisReport, locale: Locale = report.locale): string {
  const zh = locale === "zh-CN";
  const localized = localizeReportView(report, locale);
  const title = report.repositoryName
    ? `${zh ? "AgentLint 报告" : "AgentLint report"} — ${report.repositoryName}`
    : (zh ? "AgentLint 报告" : "AgentLint report");
  const labels = metricLabels(locale);
  const rows = Object.entries(report.metrics).map(([name, score]) => `| ${labels[name] ?? name} | ${score} |`).join("\n");
  const findings = localized.findings.length
    ? localized.findings.map((finding) => renderFindingMarkdown(finding, locale)).join("\n\n")
    : (zh ? "没有发现问题。所有已启用的确定性检查均已通过。" : "No findings. All enabled deterministic checks passed.");

  return `# ${title}\n\n` +
    `**${zh ? "评分" : "Score"}：** ${report.score}/100 — ${localized.grade}\n\n` +
    `**${zh ? "摘要" : "Summary"}：** ${report.summary.errors} ${zh ? "个错误" : "errors"}，${report.summary.warnings} ${zh ? "个警告" : "warnings"}，` +
    `${report.summary.suggestions} ${zh ? "条建议，共扫描" : "suggestions across"} ${report.summary.instructionFiles} ${zh ? "个规则文件。" : "instruction files."}\n\n` +
    `| ${zh ? "指标" : "Metric"} | ${zh ? "得分" : "Score"} |\n|---|---:|\n${rows}\n\n` +
    `## ${zh ? "问题清单" : "Findings"}\n\n${findings}\n\n` +
    `## ${zh ? "上下文估算" : "Context estimate"}\n\n` +
    `- ${zh ? "规则预计令牌数" : "Estimated instruction tokens"}：${report.summary.estimatedTokens}\n` +
    `- ${zh ? "完全重复指令" : "Exact duplicate instructions"}：${report.summary.duplicateInstructions}\n` +
    `- ${zh ? "预计可减少令牌数" : "Estimated avoidable tokens"}：${report.summary.avoidableTokens}\n` +
    `- ${zh ? "安全自动修复" : "Safe automatic fixes"}：${report.summary.fixable}\n` +
    `- ${zh ? "已抑制问题" : "Suppressed findings"}：${report.summary.suppressed}\n\n` +
    `_${zh ? "生成时间" : "Generated by AgentLint at"}：${report.generatedAt}。_\n`;
}

export function renderPrettyReport(report: AnalysisReport, locale: Locale = report.locale): string {
  const zh = locale === "zh-CN";
  const localized = localizeReportView(report, locale);
  const lines = [
    "",
    `AgentLint  ${report.score}/100 (${localized.grade})${report.repositoryName ? `  ${report.repositoryName}` : ""}`,
    "",
    zh
      ? `${report.summary.errors} 个错误 · ${report.summary.warnings} 个警告 · ${report.summary.suggestions} 条建议`
      : `${report.summary.errors} errors · ${report.summary.warnings} warnings · ${report.summary.suggestions} suggestions`,
    zh
      ? `${report.summary.instructionFiles} 个规则文件 · 约 ${report.summary.estimatedTokens} 个令牌 · ${report.summary.fixable} 个安全修复`
      : `${report.summary.instructionFiles} instruction files · ~${report.summary.estimatedTokens} tokens · ${report.summary.fixable} safe fixes`,
    "",
  ];

  if (localized.findings.length === 0) {
    lines.push(zh ? "通过   未发现已启用的确定性问题。" : "PASS   No enabled deterministic issues found.");
  } else {
    for (const finding of localized.findings) {
      const label = finding.severity === "error" ? (zh ? "错误 " : "ERROR") : finding.severity === "warning" ? (zh ? "警告 " : "WARN ") : (zh ? "建议 " : "INFO ");
      lines.push(`${label}  ${finding.title}  [${finding.ruleId}]`);
      if (finding.file) lines.push(`       ${finding.file}${finding.line ? `:${finding.line}` : ""}${finding.evidence ? ` — ${finding.evidence.replaceAll("\n", " | ")}` : ""}`);
      if (finding.suggestion) lines.push(`       ${zh ? "修复" : "Fix"}: ${finding.suggestion}`);
      if (finding.fix?.safe) lines.push(zh ? "       可使用 --fix 自动修复" : "       Auto-fix available with --fix");
      lines.push("");
    }
  }
  return lines.join("\n");
}

export function renderGitHubAnnotations(report: AnalysisReport, locale: Locale = report.locale): string {
  const localized = localizeReportView(report, locale);
  return localized.findings.map((finding) => {
    const command = finding.severity === "error" ? "error" : finding.severity === "warning" ? "warning" : "notice";
    const properties = [
      finding.file ? `file=${escapeProperty(finding.file)}` : "",
      finding.line ? `line=${finding.line}` : "",
      `title=${escapeProperty(`AgentLint ${finding.ruleId}`)}`,
    ].filter(Boolean).join(",");
    return `::${command} ${properties}::${escapeMessage(`${finding.title}: ${finding.message}`)}`;
  }).join("\n");
}

export function renderSarifReport(report: AnalysisReport, locale: Locale = report.locale): string {
  const localized = localizeReportView(report, locale);
  const ruleMap = new Map<string, Finding>();
  for (const finding of localized.findings) if (!ruleMap.has(finding.ruleId)) ruleMap.set(finding.ruleId, finding);
  const sarif = {
    $schema: "https://json.schemastore.org/sarif-2.1.0.json",
    version: "2.1.0",
    runs: [{
      tool: {
        driver: {
          name: "AgentLint",
          informationUri: "https://github.com/valseeee/agentlint",
          semanticVersion: "0.4.0",
          rules: [...ruleMap.entries()].map(([id, finding]) => ({
            id,
            name: id.replaceAll("/", "_"),
            shortDescription: { text: finding.title },
            helpUri: finding.docs,
            defaultConfiguration: { level: sarifLevel(finding.severity) },
          })),
        },
      },
      results: localized.findings.map((finding) => ({
        ruleId: finding.ruleId,
        level: sarifLevel(finding.severity),
        message: { text: `${finding.title}: ${finding.message}` },
        locations: finding.file ? [{
          physicalLocation: {
            artifactLocation: { uri: finding.file },
            region: finding.line ? { startLine: finding.line } : undefined,
          },
        }] : undefined,
      })),
    }],
  };
  return JSON.stringify(sarif, null, 2);
}

export function renderDiffMarkdown(diff: ReportDiff, locale: Locale = "en-US"): string {
  const zh = locale === "zh-CN";
  const section = (title: string, findings: Finding[]) => findings.length
    ? `## ${title}\n\n${findings.map((finding) => `- **${finding.title}** \`${finding.ruleId}\`${finding.file ? ` — \`${finding.file}${finding.line ? `:${finding.line}` : ""}\`` : ""}`).join("\n")}`
    : `## ${title}\n\n${zh ? "无。" : "None."}`;
  return `# ${zh ? "AgentLint 基线差异" : "AgentLint baseline diff"}\n\n` +
    `**${zh ? "评分变化" : "Score delta"}：** ${diff.scoreDelta >= 0 ? "+" : ""}${diff.scoreDelta}\n\n` +
    `${section(zh ? `新增问题（${diff.added.length}）` : `Added findings (${diff.added.length})`, diff.added)}\n\n` +
    `${section(zh ? `已解决问题（${diff.resolved.length}）` : `Resolved findings (${diff.resolved.length})`, diff.resolved)}\n`;
}

export function localizeReportView(report: AnalysisReport, locale: Locale): AnalysisReport {
  const findings = report.findings.map((finding) => {
    const text = finding.translations?.[locale];
    return text ? {
      ...finding,
      title: text.title,
      message: text.message,
      suggestion: text.suggestion,
      fix: finding.fix ? { ...finding.fix, description: finding.fix.translations?.[locale] ?? finding.fix.description } : undefined,
    } : finding;
  });
  const grade = locale === "zh-CN"
    ? ({ excellent: "优秀", good: "良好", "needs-work": "需要改进", critical: "问题严重" } as const)[report.gradeKey]
    : ({ excellent: "Excellent", good: "Good", "needs-work": "Needs work", critical: "Critical" } as const)[report.gradeKey];
  const instructionFiles = report.instructionFiles.map((file) => ({
    ...file,
    label: instructionLabel(file.kind, locale),
    scope: localizeScope(file.scope, locale),
  }));
  const scopeGraph = {
    ...report.scopeGraph,
    nodes: report.scopeGraph.nodes.map((node) => ({
      ...node,
      label: instructionLabel(node.kind, locale),
      scope: localizeScope(node.scope, locale),
    })),
  };
  return { ...report, locale, grade, findings, instructionFiles, scopeGraph };
}

function localizeScope(scope: string, locale: Locale): string {
  const pairs: Record<string, [string, string]> = {
    repository: ["repository", "整个仓库"],
    "整个仓库": ["repository", "整个仓库"],
    "frontmatter paths or repository": ["frontmatter paths or repository", "文件头路径或整个仓库"],
    "文件头路径或整个仓库": ["frontmatter paths or repository", "文件头路径或整个仓库"],
    "rule metadata": ["rule metadata", "规则元数据定义"],
    "规则元数据定义": ["rule metadata", "规则元数据定义"],
    "applyTo glob": ["applyTo glob", "applyTo 匹配范围"],
    "applyTo 匹配范围": ["applyTo glob", "applyTo 匹配范围"],
    "custom agent": ["custom agent", "自定义助手"],
    "自定义助手": ["custom agent", "自定义助手"],
    always: ["always", "始终生效"],
    "始终生效": ["always", "始终生效"],
    "agent-selected": ["agent-selected", "由编程助手按描述选择"],
    "由编程助手按描述选择": ["agent-selected", "由编程助手按描述选择"],
  };
  const pair = pairs[scope];
  return pair ? pair[locale === "zh-CN" ? 1 : 0] : scope;
}

function renderFindingMarkdown(finding: Finding, locale: Locale): string {
  const zh = locale === "zh-CN";
  const icon = finding.severity === "error" ? "❌" : finding.severity === "warning" ? "⚠️" : "ℹ️";
  const location = finding.file ? `\n\n**${zh ? "位置" : "Location"}：** \`${finding.file}${finding.line ? `:${finding.line}` : ""}\`` : "";
  const evidence = finding.evidence ? `\n\n> ${finding.evidence.replaceAll("\n", "  \n> ")}` : "";
  const suggestion = finding.suggestion ? `\n\n**${zh ? "建议修复" : "Suggested fix"}：** ${finding.suggestion}` : "";
  const automatic = finding.fix?.safe ? `\n\n**${zh ? "自动修复" : "Automatic fix"}：** ${zh ? "可使用" : "Available with"} \`agentlint check . --fix\`.` : "";
  return `### ${icon} ${finding.title}\n\n\`${finding.ruleId}\`${location}\n\n${finding.message}${evidence}${suggestion}${automatic}`;
}

function metricLabels(locale: Locale): Record<string, string> {
  return locale === "zh-CN"
    ? { coverage: "配置覆盖", consistency: "一致性", validity: "有效性", security: "安全性", efficiency: "上下文效率" }
    : { coverage: "Coverage", consistency: "Consistency", validity: "Validity", security: "Security", efficiency: "Context efficiency" };
}

function sarifLevel(severity: Finding["severity"]): "error" | "warning" | "note" {
  return severity === "info" ? "note" : severity;
}

function escapeProperty(value: string): string {
  return value.replaceAll("%", "%25").replaceAll("\r", "%0D").replaceAll("\n", "%0A").replaceAll(":", "%3A").replaceAll(",", "%2C");
}

function escapeMessage(value: string): string {
  return value.replaceAll("%", "%25").replaceAll("\r", "%0D").replaceAll("\n", "%0A");
}
